-- Private order storage. Run once in the Balo Supabase project's SQL editor.
begin;
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null check (char_length(btrim(customer_name)) between 2 and 100),
  phone text not null check (char_length(phone) between 6 and 25 and phone ~ '^[+0-9 ()-]+$'),
  order_info text not null check (char_length(btrim(order_info)) between 3 and 2000),
  created_at timestamptz not null default now()
);
create table if not exists public.balo_request_limits (
  bucket text primary key,
  window_start timestamptz not null default now(),
  requests integer not null default 1
);
alter table public.orders enable row level security;
alter table public.balo_request_limits enable row level security;
revoke all on public.orders, public.balo_request_limits from public, anon, authenticated;
grant select, insert on public.orders to service_role;
revoke all on sequence public.orders_id_seq from public, anon, authenticated;
grant usage, select on sequence public.orders_id_seq to service_role;
grant select, insert, update, delete on public.balo_request_limits to service_role;

-- One atomic transaction enforces the limit across all Vercel instances.
-- The bucket is an HMAC; no raw customer IP is saved.
create or replace function public.submit_balo_order(p_name text, p_phone text, p_order_info text, p_bucket text)
returns jsonb language plpgsql security invoker set search_path = '' as $$
declare
  v_count integer;
  v_id bigint;
begin
  if p_bucket !~ '^[a-f0-9]{64}$' then raise exception 'invalid_bucket'; end if;
  insert into public.balo_request_limits as limits (bucket, window_start, requests)
    values (p_bucket, now(), 1)
    on conflict (bucket) do update set
      requests = case when limits.window_start < now() - interval '15 minutes' then 1 else limits.requests + 1 end,
      window_start = case when limits.window_start < now() - interval '15 minutes' then now() else limits.window_start end
    returning requests into v_count;
  if v_count > 10 then raise exception 'balo_rate_limited'; end if;
  insert into public.orders (customer_name, phone, order_info)
    values (btrim(p_name), btrim(p_phone), btrim(p_order_info)) returning id into v_id;
  delete from public.balo_request_limits where window_start < now() - interval '1 day';
  return jsonb_build_object('orderId', v_id::text);
end;
$$;
revoke all on function public.submit_balo_order(text,text,text,text) from public, anon, authenticated;
grant execute on function public.submit_balo_order(text,text,text,text) to service_role;
commit;
